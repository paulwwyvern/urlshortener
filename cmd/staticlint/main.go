func main() {
	vetChecks := []*analysis.Analyzer{
		appends.Analyzer,
		asmdecl.Analyzer,
		assign.Analyzer,
		atomic.Analyzer,
		bools.Analyzer,
		buildtag.Analyzer,
		cgocall.Analyzer,
		composite.Analyzer,
		copylock.Analyzer,
		defers.Analyzer,
		directive.Analyzer,
		errorsas.Analyzer,
		framepointer.Analyzer,
		hostport.Analyzer,
		httpresponse.Analyzer,
		ifaceassert.Analyzer,
		loopclosure.Analyzer,
		lostcancel.Analyzer,
		nilfunc.Analyzer,
		printf.Analyzer,
		shift.Analyzer,
		sigchanyzer.Analyzer,
		slog.Analyzer,
		stdmethods.Analyzer,
		stringintconv.Analyzer,
		structtag.Analyzer,
		testinggoroutine.Analyzer,
		tests.Analyzer,
		timeformat.Analyzer,
		unmarshal.Analyzer,
		unreachable.Analyzer,
		unsafeptr.Analyzer,
		unusedresult.Analyzer,
		waitgroup.Analyzer,
	}

	staticChecks := []*analysis.Analyzer{}

	for _, v := range staticcheck.Analyzers {
		staticChecks = append(staticChecks, v.Analyzer)
	}

	for _, v := range simple.Analyzers {
		staticChecks = append(staticChecks, v.Analyzer)
	}

	stBlacklist := map[string]bool{
		"ST1000": true,
	}
	for _, v := range stylecheck.Analyzers {
		if stBlacklist[v.Analyzer.Name] {
			continue
		}

		staticChecks = append(staticChecks, v.Analyzer)
	}

	for _, a := range quickfix.Analyzers {
		staticChecks = append(staticChecks, a.Analyzer)
	}

	var mychecks []*analysis.Analyzer

	mychecks = append(mychecks, staticChecks...)
	mychecks = append(mychecks, vetChecks...)

	var noexitCheck = noexit.Analyzer

	mychecks = append(mychecks, noexitCheck)

	multichecker.Main(
		mychecks...,
	)
}
